#!/usr/bin/env python3
"""Build the golden test set for the HR Ops Agent evaluation harness.

Usage:
    uv run python eval/golden/build_golden.py > eval/golden/golden_set.jsonl
    # or, from the project root:
    python eval/golden/build_golden.py > eval/golden/golden_set.jsonl

Produces eval/golden/golden_set.jsonl — 150 queries across 5 categories:
  - spd_001..030 : search_process_docs (30 queries)
  - lki_001..030 : lookup_known_issues (30 queries)
  - its_001..030 : get_it_scope (30 queries)
  - gep_001..030 : get_escalation_path (30 queries)
  - adv_001..030 : adversarial / multi-tool / edge-case (30 queries)

Schema per entry:
  id                    : unique identifier (category_NNN)
  type                  : "tool_use" | "multi_step"
  instruction           : the user query text
  allowed_tools         : all 4 tools (always the full set)
  required_tools        : tools that MUST be called for a pass
  expected_tool_sequence: ordered [{tool, args_contains}] — args_contains is
                          a dict of arg_name -> substring to check (case-insensitive)
  expected_answer_contains : list of substrings that should appear in the answer
  expected_answer_excludes : list of substrings that must NOT appear
  answer_type           : "procedural" | "factual" | "contact" | "diagnostic"
  notes                 : reviewer notes (oracle rationale, edge-case explanation)
  requires_refusal      : bool — out-of-scope query that must be actively
                          refused; drives the policy_miss classification

Oracle labels: generated by Claude Sonnet (2026-06-03), reviewed by Nicolas Duarte.
Routing labels are the authoritative ground truth; answer-content labels are
best-effort (agent knowledge base may not contain all expected terms).
"""
